from collections import defaultdict

class Graph:
    def __init__(self):
        self.adj = defaultdict(dict)

    def add_edge(self, u, v, distance):
        self.adj[u][v] = distance
        self.adj[v][u] = distance

    def resolve(self, name):
        lookup = {city.lower(): city for city in self.adj}

        if name.lower() in lookup:
            return lookup[name.lower()]

        raise KeyError(f"City '{name}' not found.")

"""Building  the Indian-city graph from data"""

