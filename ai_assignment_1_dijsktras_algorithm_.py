"""implementation Dijkstra"""

from heapq import heappush, heappop
from math import inf

def dijkstra(graph, source, target=None):

    dist = {source: 0}
    parent = {source: None}

    heap = [(0, source)]
    visited = set()

    while heap:

        current_distance, current_city = heappop(heap)

        if current_city in visited:
            continue

        visited.add(current_city)

        if current_city == target:
            break

        for neighbor, road_distance in graph.adj[current_city].items():

            new_distance = current_distance + road_distance

            if new_distance < dist.get(neighbor, inf):

                dist[neighbor] = new_distance
                parent[neighbor] = current_city

                heappush(heap, (new_distance, neighbor))

    return dist, parent

"""the path function"""

def build_path(parent, city):

    path = []

    while city is not None:
        path.append(city)
        city = parent[city]

    return path[::-1]

